test('flow corrects an entry and then cancels it', async ({ browser }) => {
  const { context, page } = await open(browser)
  await page.goto('/lancamentos?month=2026-10')
  await page.getByRole('button', { name: 'Corrigir Internet' }).click()
  const form = page.getByRole('form', { name: 'Corrigir Internet' })
  await form.getByLabel('Valor').fill('135,00')
  await form.getByRole('button', { name: 'Salvar correção' }).click()
  await expect(page.getByRole('status')).toContainText('Corrigido: Internet')
  await expect(page.getByRole('table').getByRole('row', { name: /Internet/ })).toContainText('R$ 135,00')
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Corrigir Internet' }).click()
  await page.getByRole('button', { name: 'Cancelar lançamento' }).click()
  await expect(page.getByRole('status')).toContainText('Cancelado: Internet')
  await expect(page.getByRole('table').getByRole('row', { name: /Internet/ })).toHaveCount(0)
  await page.goto('/atividade')
  await expect(page.getByRole('main')).toContainText('Internet')
  await context.close()
})

test('flow registers a category and a recurring expense, edits and closes them, then reuses the closed name', async ({ browser }) => {
  const { context, page } = await open(browser)
  await page.goto('/cadastros')
  await page.getByLabel('O que cadastrar').selectOption('category')
  const category = page.getByRole('form', { name: 'Cadastrar categoria' })
  await category.getByLabel('Nome').fill('Pets')
  await category.getByRole('button', { name: 'Cadastrar' }).click()
  await expect(page.getByRole('status')).toContainText('Cadastrado: Pets')
  await page.getByLabel('O que cadastrar').selectOption('recurring_expense')
  const expense = page.getByRole('form', { name: 'Cadastrar despesa fixa' })
  await expense.getByLabel('Descrição').fill('Ração')
  await expense.getByLabel('Valor mensal').fill('250,00')
  await expense.getByLabel('Dia do mês').fill('12')
  await expense.getByLabel('Início').fill('2026-11-01')
  await expense.getByLabel('Categoria').fill('Pets')
  await expense.getByRole('button', { name: 'Cadastrar' }).click()
  await expect(page.getByRole('status')).toContainText('Cadastrado: Ração')
  const fixed = page.getByRole('region', { name: /Despesas fixas/ })
  await expect(fixed).toContainText('R$ 250,00 por mês · dia 12 · Pets · Conjunto')
  await fixed.getByRole('button', { name: 'Editar Ração' }).click()
  const edit = fixed.getByRole('form', { name: 'Editar Ração' })
  await edit.getByLabel('Valor mensal').fill('275,00')
  await edit.getByLabel('Dia do mês').fill('15')
  await edit.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByRole('status')).toContainText('Alterado: Ração')
  await expect(fixed).toContainText('R$ 275,00 por mês · dia 15 · Pets · Conjunto')
  page.once('dialog', (dialog) => dialog.accept())
  await fixed.getByRole('button', { name: 'Encerrar Ração' }).click()
  await expect(page.getByRole('status')).toContainText('Encerrado: Ração')
  await expect(fixed.getByText('Ração')).toHaveCount(0)
  page.once('dialog', (dialog) => dialog.accept())
  await page
    .getByRole('region', { name: /Categorias/ })
    .getByRole('button', { name: 'Encerrar Pets' })
    .click()
  await expect(page.getByRole('status')).toContainText('Encerrado: Pets')
  await page.getByLabel('O que cadastrar').selectOption('category')
  await page.getByRole('form', { name: 'Cadastrar categoria' }).getByLabel('Nome').fill('Pets')
  await page.getByRole('form', { name: 'Cadastrar categoria' }).getByRole('button', { name: 'Cadastrar' }).click()
  await expect(page.getByRole('status')).toContainText('Cadastrado: Pets')
  await context.close()
})
